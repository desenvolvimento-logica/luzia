-- Corpo das funções reconstruído a partir da spec operacional (o inventário mostra só nomes e gatilhos).
insert into public.dpto (dpto_name, user_create) values ('Não atribuído', 'auto-provisionamento-azure-ad');

create function public.link_auth_user_to_app_user() returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  v_dpto bigint;
begin
  update public.users set auth_user_id = new.id
   where lower(user_email) = lower(new.email) and auth_user_id is null;
  if not found and not exists (select 1 from public.users where auth_user_id = new.id) then
    select dpto_id into v_dpto from public.dpto where dpto_name = 'Não atribuído';
    insert into public.users (auth_user_id, user_name, user_email, user_dpto, user_role, is_admin, user_create)
    values (
      new.id,
      coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name', split_part(new.email, '@', 1)),
      lower(new.email), v_dpto, 'usuario', false, 'auto-provisionamento-azure-ad'
    );
  end if;
  return new;
end
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.link_auth_user_to_app_user();

-- Gatilho inverso (AFTER INSERT, como no inventário): cadastro criado depois de a pessoa já ter conta em auth.users.
create function public.link_app_user_to_auth_user() returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  if new.auth_user_id is null then
    update public.users u
       set auth_user_id = a.id
      from auth.users a
     where u.user_id = new.user_id and lower(a.email) = lower(new.user_email)
       and not exists (select 1 from public.users x where x.auth_user_id = a.id);
  end if;
  return null;
end
$$;

create trigger on_app_user_created
  after insert on public.users
  for each row execute function public.link_app_user_to_auth_user();
