begin
  if to_regclass('public.users') is not null or to_regclass('public.dpto') is not null then
    raise exception 'baseline legado: tabelas do hub já existem; use apenas supabase/migrations em bancos existentes';
  end if;
end
$$;

create table public.dpto (
  dpto_id bigint generated always as identity primary key,
  dpto_name character varying not null,
  dt_create timestamptz not null default now(),
  user_create character varying,
  constraint dpto_dpto_name_key unique (dpto_name)
);

create table public.users (
  user_id bigint generated always as identity primary key,
  auth_user_id uuid references auth.users (id),
  user_name character varying not null,
  user_email character varying not null,
  user_dpto bigint not null references public.dpto (dpto_id),
  user_role character varying not null,
  is_admin boolean not null default false,
  dt_create timestamptz not null default now(),
  user_create character varying,
  constraint users_auth_user_id_key unique (auth_user_id),
  constraint users_user_email_key unique (user_email),
  constraint users_user_role_check check (user_role::text = any (array['usuario', 'lider', 'coordenador', 'gerente', 'diretor']::text[]))
);
create index idx_users_auth_user_id on public.users (auth_user_id);
create index idx_users_dpto on public.users (user_dpto);

create table public.applications (
  app_id bigint generated by default as identity primary key,
  app_name character varying not null,
  app_description text,
  app_url text not null,
  app_icon text,
  app_status boolean not null default true,
  dt_created timestamptz not null default now(),
  user_created character varying
);

create table public.applications_dpto (
  app_id bigint not null references public.applications (app_id) on delete cascade,
  dpto_id bigint not null references public.dpto (dpto_id) on delete cascade,
  primary key (app_id, dpto_id)
);

create table public.access_log (
  log_id bigint generated by default as identity primary key,
  user_id bigint not null references public.users (user_id) on delete cascade,
  app_id bigint not null references public.applications (app_id) on delete cascade,
  datetime timestamptz not null default now()
);
create index idx_access_log_app on public.access_log (app_id);
create index idx_access_log_datetime on public.access_log (datetime desc);
create index idx_access_log_user on public.access_log (user_id);

create table public.patch_notes (
  note_id bigint generated by default as identity primary key,
  note_title character varying not null,
  note_body text not null,
  note_version character varying,
  dt_publish timestamptz not null default now(),
  user_create character varying
);
create index idx_patch_notes_dt_publish on public.patch_notes (dt_publish desc);

-- Funções SECURITY DEFINER do legado (search_path = public, como no inventário; sem verificação de estado).
create function public.current_user_id() returns bigint
language sql stable security definer set search_path = public
as $$ select user_id from public.users where auth_user_id = auth.uid() $$;

create function public.current_user_role() returns character varying
language sql stable security definer set search_path = public
as $$ select user_role from public.users where auth_user_id = auth.uid() $$;

create function public.current_user_dpto() returns bigint
language sql stable security definer set search_path = public
as $$ select user_dpto from public.users where auth_user_id = auth.uid() $$;

create function public.current_user_is_admin() returns boolean
language sql stable security definer set search_path = public
as $$ select coalesce((select is_admin from public.users where auth_user_id = auth.uid()), false) $$;

