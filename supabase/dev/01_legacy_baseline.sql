create policy users_admin_write on public.users for all to authenticated
  using (current_user_is_admin()) with check (current_user_is_admin());
create policy users_select_scoped on public.users for select to authenticated using (
  (auth_user_id = auth.uid()) or current_user_is_admin()
  or ((current_user_role())::text = any (array['diretor', 'gerente']::text[]))
  or (((current_user_role())::text = 'coordenador') and (user_dpto = current_user_dpto()) and ((user_role)::text = any (array['usuario', 'lider']::text[])))
  or (((current_user_role())::text = 'lider') and (user_dpto = current_user_dpto()) and ((user_role)::text = 'usuario'))
);

create policy applications_admin_write on public.applications for all to authenticated
  using (current_user_is_admin()) with check (current_user_is_admin());
create policy applications_select_scoped on public.applications for select to authenticated using (
  current_user_is_admin()
  or ((app_status = true) and (
        (not (exists (select 1 from applications_dpto ad where ad.app_id = applications.app_id)))
     or (exists (select 1 from applications_dpto ad where ad.app_id = applications.app_id and ad.dpto_id = current_user_dpto()))))
);

create policy access_log_admin_write on public.access_log for all to authenticated
  using (current_user_is_admin()) with check (current_user_is_admin());
create policy access_log_select_scoped on public.access_log for select to authenticated using (
  exists (select 1 from users u where u.user_id = access_log.user_id and (
    (u.auth_user_id = auth.uid()) or current_user_is_admin()
    or ((current_user_role())::text = any (array['diretor', 'gerente']::text[]))
    or (((current_user_role())::text = 'coordenador') and (u.user_dpto = current_user_dpto()) and ((u.user_role)::text = any (array['usuario', 'lider']::text[])))
    or (((current_user_role())::text = 'lider') and (u.user_dpto = current_user_dpto()) and ((u.user_role)::text = 'usuario'))))
);
create policy access_log_self_insert on public.access_log for insert to authenticated
  with check (user_id = current_user_id());

