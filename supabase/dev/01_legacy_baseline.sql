create table public.dpto (
  dpto_id bigint generated by default as identity primary key,
  dpto_name text not null unique,
  dt_create timestamptz not null default now(),
  user_create text
);

create table public.users (
  user_id bigint generated by default as identity primary key,
  auth_user_id uuid unique references auth.users (id),
  user_name text not null,
  user_email text not null unique,
  user_dpto bigint references public.dpto (dpto_id),
  user_role text not null default 'usuario'
    check (user_role in ('usuario', 'lider', 'coordenador', 'gerente', 'diretor')),
  is_admin boolean not null default false,
  dt_create timestamptz not null default now(),
  user_create text
);

create table public.applications (
  app_id bigint generated by default as identity primary key,
  app_name text not null,
  app_description text,
  app_url text not null,
  app_icon text,
  app_status boolean not null default true,
  dt_created timestamptz not null default now(),
  user_created text
);

create table public.applications_dpto (
  app_id bigint not null references public.applications (app_id),
  dpto_id bigint not null references public.dpto (dpto_id),
  primary key (app_id, dpto_id)
);

create table public.access_log (
  log_id bigint generated by default as identity primary key,
  user_id bigint not null references public.users (user_id),
  app_id bigint not null references public.applications (app_id),
  datetime timestamptz not null default now()
);
create index access_log_user_idx on public.access_log (user_id);
create index access_log_app_idx on public.access_log (app_id);
create index access_log_datetime_idx on public.access_log (datetime);

create table public.patch_notes (
  note_id bigint generated by default as identity primary key,
  note_title text not null,
  note_body text not null,
  note_version text,
  dt_publish timestamptz not null default now(),
  user_create text
);

-- Funções SECURITY DEFINER do legado (no schema public, como descrito; sem verificação de estado).
create function public.current_user_id() returns bigint
language sql stable security definer set search_path = public
as $$ select user_id from public.users where auth_user_id = auth.uid() $$;

create function public.current_user_role() returns text
language sql stable security definer set search_path = public
as $$ select user_role from public.users where auth_user_id = auth.uid() $$;

create function public.current_user_dpto() returns bigint
language sql stable security definer set search_path = public
as $$ select user_dpto from public.users where auth_user_id = auth.uid() $$;

create function public.current_user_is_admin() returns boolean
language sql stable security definer set search_path = public
as $$ select coalesce((select is_admin from public.users where auth_user_id = auth.uid()), false) $$;

alter table public.dpto enable row level security;
alter table public.users enable row level security;
alter table public.applications enable row level security;
alter table public.applications_dpto enable row level security;
alter table public.access_log enable row level security;
alter table public.patch_notes enable row level security;

create policy legacy_dpto_select on public.dpto for select to authenticated using (true);
create policy legacy_dpto_write on public.dpto for all to authenticated
  using (public.current_user_is_admin()) with check (public.current_user_is_admin());

create policy legacy_apps_dpto_select on public.applications_dpto for select to authenticated using (true);
create policy legacy_apps_dpto_write on public.applications_dpto for all to authenticated
  using (public.current_user_is_admin()) with check (public.current_user_is_admin());

create policy legacy_patch_notes_select on public.patch_notes for select to authenticated using (true);
create policy legacy_patch_notes_write on public.patch_notes for all to authenticated
  using (public.current_user_is_admin()) with check (public.current_user_is_admin());

create policy legacy_users_select on public.users for select to authenticated using (
  auth_user_id = auth.uid()
  or public.current_user_is_admin()
  or public.current_user_role() in ('diretor', 'gerente')
  or (public.current_user_role() = 'coordenador' and user_dpto = public.current_user_dpto() and user_role in ('usuario', 'lider'))
  or (public.current_user_role() = 'lider' and user_dpto = public.current_user_dpto() and user_role = 'usuario')
);
create policy legacy_users_write on public.users for all to authenticated
  using (public.current_user_is_admin()) with check (public.current_user_is_admin());

create policy legacy_apps_select on public.applications for select to authenticated using (
  public.current_user_is_admin()
  or (
    app_status
    and (
      not exists (select 1 from public.applications_dpto d where d.app_id = applications.app_id)
      or exists (select 1 from public.applications_dpto d where d.app_id = applications.app_id and d.dpto_id = public.current_user_dpto())
    )
  )
);
create policy legacy_apps_write on public.applications for all to authenticated
  using (public.current_user_is_admin()) with check (public.current_user_is_admin());

create policy legacy_access_log_select on public.access_log for select to authenticated using (
  exists (select 1 from public.users u where u.user_id = access_log.user_id)
);
create policy legacy_access_log_insert on public.access_log for insert to authenticated
  with check (user_id = public.current_user_id());
create policy legacy_access_log_admin on public.access_log for update to authenticated
  using (public.current_user_is_admin());
create policy legacy_access_log_admin_delete on public.access_log for delete to authenticated
  using (public.current_user_is_admin());

-- Auto-provisionamento legado (auto-provisionamento.sql): vincula por e-mail ou cria usuario/"Não atribuído".
insert into public.dpto (dpto_name, user_create) values ('Não atribuído', 'auto-provisionamento-azure-ad');

create function public.link_auth_user_to_app_user() returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  v_dpto bigint;
begin
  update public.users set auth_user_id = new.id
   where lower(user_email) = lower(new.email) and auth_user_id is null;
  if not found and not exists (select 1 from public.users where auth_user_id = new.id) then
    select dpto_id into v_dpto from public.dpto where dpto_name = 'Não atribuído';
    insert into public.users (auth_user_id, user_name, user_email, user_dpto, user_role, is_admin, user_create)
    values (
      new.id,
      coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name', split_part(new.email, '@', 1)),
      lower(new.email), v_dpto, 'usuario', false, 'auto-provisionamento-azure-ad'
    );
  end if;
  return new;
end
$$;

create trigger on_auth_user_created_link_hub
  after insert on auth.users
  for each row execute function public.link_auth_user_to_app_user();
